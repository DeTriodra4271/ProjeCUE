let currentLang = 'tr';

function detectLanguage() {
    const l = String(navigator.language || '').slice(0, 2).toLowerCase();
    return STRINGS[l] ? l : 'en';
}

function t(key, vars) {
    let s = STRINGS[currentLang] && STRINGS[currentLang][key];
    if (s === undefined) s = STRINGS.en[key];
    if (s === undefined) return key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

// data-i18n / -placeholder / -title / -aria ozelliklerini doldurur, sonra dinleyicileri cagirir
const langListeners = [];
function applyLanguage(lang) {
    if (!STRINGS[lang]) lang = detectLanguage();
    currentLang = lang;
    document.documentElement.lang = lang;   // büyük/küçük harf (tr: İ/ı) ve yazım denetimi için
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    document.querySelectorAll('.lang-pick').forEach(sel => { if (sel.value !== lang) sel.value = lang; });
    langListeners.forEach(fn => fn(lang));
}
